"""Debug information for GnuCOBOL: variable map, data layout and launch.json."""
import json
import os
import re
import shlex
import subprocess

from .messages import SCHEMA, VERSION

LAUNCH_NAME = "Cobalto: debug {suite}"
VARS_RE = re.compile(r"static\s+cob_u8_t\s+(b_\d+)\[(\d+)\][^;]*;\s*/\*\s*(.+?)\s*\*/")
FIELD_RE = re.compile(r"static\s+cob_field\s+(f_\d+)\s*=\s*\{(\d+),\s*(b_\d+|NULL)[^;]*;\s*/\*\s*(.+?)\s*\*/")
PARM_RE = re.compile(r"cob_parm_(\d+)\s*=\s*NULL;\s*/\*\s*linkage for\s+(.+?)\s*\*/")


def cobol_vars_map(build, prog):
    """GnuCOBOL keeps each WORKING-STORAGE item as a static b_NNN (in
    <program>.c.l.h) and, if it uses it as a field, a cob_field descriptor
    f_NNN; LINKAGE items arrive as b_NNN parameters of the function (in
    <program>.c). Each program has its own numbering. Returns
    (name, section, b_NNN, f_NNN or "", bytes or 0)."""
    header = os.path.join(build, f"{prog}.c.l.h")
    if not os.path.exists(header):
        return []
    with open(header, encoding="utf-8", errors="replace") as fh:
        text = fh.read()
    fields = {}
    for m in FIELD_RE.finditer(text):
        fields[m.group(4)] = (m.group(1), int(m.group(2)), m.group(3) == "NULL")
    rows = []
    for m in VARS_RE.finditer(text):
        name = m.group(3)
        rows.append((name, "Globals", m.group(1), fields.get(name, ("",))[0], int(m.group(2))))
    csrc = os.path.join(build, f"{prog}.c")
    if os.path.exists(csrc):
        with open(csrc, encoding="utf-8", errors="replace") as fh:
            ctext = fh.read()
        for m in PARM_RE.finditer(ctext):
            name = m.group(2)
            fld = fields.get(name)
            rows.append((name, "Locals", "b_" + m.group(1), fld[0] if fld else "", fld[1] if fld else 0))
    return rows


def format_vars_map(targets, build):
    """Text of <suite>.vars.txt: one block per program with the COBOL field,
    the panel where it shows, the static with the bytes, the descriptor and
    the expression for the debug console."""
    out = ["COBOL variables -> C generated by cobc. Each program numbers its b_NNN/f_NNN",
           "on its own: f_18 of DISCOUNT does not exist inside TSTINV. The expressions",
           "are valid with the stack frame stopped in that program.",
           "  Globals = WORKING-STORAGE, Locals = LINKAGE parameters.",
           "  console: value formatted by libcob if there is a descriptor; otherwise, the raw bytes.",
           "  For a LINKAGE parameter the descriptor only points to the data once the",
           "  program has touched the field; before that, use the bytes: *(char(*)[N])b_NNN.",
           ""]
    for t in targets:
        rows = cobol_vars_map(build, t)
        if not rows:
            continue
        out.append(f"{t} ({len(rows)} items):")
        out.append(f"  {'field':32s} {'panel':8s} {'bytes':8s} {'descr.':8s} {'size':>6s}  console")
        for name, panel, b, f, n in rows:
            if f and panel == "Globals":
                expr = f"(char*)cob_get_field_str_buffered(&{f})"
            elif n:
                expr = f"*(char(*)[{n}]){b}"
            else:
                expr = f"(char*){b}"
            out.append(f"  {name:32s} {panel:8s} {b:8s} {f or '-':8s} {n or '?':>6}  {expr}")
        out.append("")
    return "\n".join(out) + "\n" if len(out) > 6 else ""


# --- data layout for the debugger ----------------------------------------
# cobc only emits a cob_field descriptor for the fields the program
# references; the symbol listing (cobc -t X.lst -ftsymbols) has every item
# with its level, size, PIC, usage, OCCURS and REDEFINES. From it comes
# build/<suite>.layout.json with the offset of each item inside its 01,
# which the VS Code extension uses to show and to write any field.
SYM_SECTION_RE = re.compile(r"^\s+(WORKING-STORAGE|LOCAL-STORAGE|LINKAGE|FILE|SCREEN|REPORT|COMMUNICATION)\s+SECTION\s*$")
SYM_PROGRAM_RE = re.compile(r"^\s+PROGRAM\s+(\S+)\s*$")
SYM_PROGRAM_ID_RE = re.compile(r"PROGRAM-ID\.\s+([A-Za-z0-9_-]+)")
SYM_ITEM_RE = re.compile(r"^(\d{5,}|\s{5})\s+([A-Z][A-Z ]*?)\s+(\d\d)\s+([A-Za-z0-9_-]+)(?:,\s*REDEFINES\s+([A-Za-z0-9_-]+))?\s*(.*?)\s*$")
SYM_USAGES = ("COMP-3", "PACKED-DECIMAL", "COMP-5", "COMP-6", "COMP-1", "COMP-2", "COMP-X", "COMP-N", "BINARY", "COMP", "DISPLAY")


def parse_symbol_listing(text):
    """Reads the symbols of a cobc -ftsymbols listing: {program: [items]},
    each item a dict with level, name, section, listed size, type, PIC,
    usage, occurs and redefines, in source order."""
    programs = {}
    ids = [m.group(1).upper() for m in SYM_PROGRAM_ID_RE.finditer(text)]
    current, section, in_table = None, None, False
    table_count = 0
    for line in text.splitlines():
        if line.startswith("SIZE  TYPE"):
            in_table = True
            table_count += 1
            if current is None or len(ids) == 1:
                current = ids[0] if ids else "?"
                programs.setdefault(current, [])
            continue
        if not in_table:
            continue
        m = SYM_PROGRAM_RE.match(line)
        if m:
            current = m.group(1).upper()
            programs.setdefault(current, [])
            continue
        m = SYM_SECTION_RE.match(line)
        if m:
            section = m.group(1)
            continue
        if line.startswith("GnuCOBOL") or line.startswith("Error/Warning") or "warnings in compilation group" in line:
            in_table = False
            continue
        m = SYM_ITEM_RE.match(line)
        if not m or current is None:
            continue
        size = int(m.group(1)) if m.group(1).strip() else 0
        rest = m.group(6)
        occurs = 0
        mo = re.search(r"OCCURS\s+(\d+)", rest)
        if mo:
            occurs = int(mo.group(1))
            rest = (rest[:mo.start()] + rest[mo.end():]).strip(" ,")
        usage = "DISPLAY"
        for u in SYM_USAGES:
            mu = re.search(r"(?<![A-Z0-9-])" + re.escape(u) + r"(?![A-Z0-9-])", rest)
            if mu:
                usage = {"PACKED-DECIMAL": "COMP-3", "BINARY": "COMP"}.get(u, u)
                rest = (rest[:mu.start()] + rest[mu.end():]).strip(" ,")
                break
        programs[current].append({
            "level": int(m.group(3)), "name": m.group(4).upper(), "section": section,
            "listed_size": size, "type": m.group(2).strip(), "pic": rest.strip(),
            "usage": usage, "occurs": occurs, "redefines": (m.group(5) or "").upper() or None,
        })
    return programs


def pic_shape(pic):
    """(digits, scale, signed) of a numeric PIC; (0, 0, False) if it is not numeric."""
    if not pic:
        return 0, 0, False
    signed = pic.startswith("S")
    body = pic[1:] if signed else pic
    expanded = re.sub(r"([A-Za-z9.,+\-*$/])\((\d+)\)", lambda m: m.group(1) * int(m.group(2)), body)
    if "V" in expanded:
        left, right = expanded.split("V", 1)
    else:
        left, right = expanded, ""
    nines_l = left.count("9") + left.count("P")
    nines_r = right.count("9")
    return nines_l + nines_r, nines_r, signed


def item_kind(it):
    t, pic, usage = it["type"], it["pic"], it["usage"]
    if t == "GROUP":
        return "group"
    if t == "POINTER":
        return "pointer"
    if t == "NUMERIC":
        if usage == "COMP-1":
            return "float"
        if usage == "COMP-2":
            return "double"
        if not pic:
            return "index"
        if re.search(r"[Z*,.+\-$/B]|CR|DB", pic.replace("V", "")):
            return "numedit"
        return {"COMP-3": "comp3", "COMP": "binary", "COMP-5": "comp5", "COMP-X": "binary", "COMP-N": "binary", "COMP-6": "comp3"}.get(usage, "display")
    return "alnum"


def build_layout(items):
    """Tree of the items of a program with their offsets: levels 66 and 88
    are skipped; a GROUP with OCCURS lists its total size and an elementary
    item with OCCURS lists the size of one occurrence. Returns (01s, warnings)."""
    roots, stack, warnings = [], [], []

    def node(it):
        kind = item_kind(it)
        digits, scale, signed = pic_shape(it["pic"]) if kind in ("display", "comp3", "binary", "comp5", "numedit") else (0, 0, False)
        n = {"name": it["name"], "level": it["level"], "section": it["section"], "kind": kind,
             "pic": it["pic"], "usage": it["usage"], "size": it["listed_size"], "occurs": it["occurs"],
             "redefines": it["redefines"], "digits": digits, "scale": scale, "signed": signed,
             "offset": 0, "children": []}
        if kind == "group" and it["occurs"] and it["listed_size"]:
            n["size"] = it["listed_size"] // it["occurs"]
        if kind == "display" and digits and it["listed_size"] == digits + 1:
            n["sign_separate"] = True
        return n

    for it in items:
        if it["level"] in (66, 88) or it["type"] == "CONDITIONAL":
            continue
        n = node(it)
        if it["level"] in (1, 77) or not stack:
            roots.append(n)
            stack = [n]
            continue
        while stack and stack[-1]["level"] >= it["level"]:
            stack.pop()
        if not stack:
            roots.append(n)
            stack = [n]
            continue
        stack[-1]["children"].append(n)
        stack.append(n)

    def total(n):
        return n["size"] * (n["occurs"] or 1)

    def place(n, base):
        n["offset"] = base
        cursor, end = base, base
        for c in n["children"]:
            if c["redefines"]:
                target = next((x for x in n["children"] if x["name"] == c["redefines"]), None)
                place(c, target["offset"] if target else cursor)
            else:
                place(c, cursor)
                cursor = c["offset"] + total(c)
            end = max(end, c["offset"] + total(c))
        if n["children"] and n["size"] and end - base != n["size"]:
            warnings.append(f"{n['name']}: its children take {end - base} bytes and the group is {n['size']}")
            n["unreliable"] = True

    for r in roots:
        place(r, 0)
    return roots, warnings


def write_layout(cfg, prof, build, suite, files, targets):
    """Runs cobc -fsyntax-only -ftsymbols on each source and writes
    build/<suite>.layout.json with the 01 items of each program."""
    std = re.search(r"(-std=\S+)", prof.get("compile", ""))
    free = " -free" if " -free" in prof.get("compile", "") else ""
    incl = " ".join("-I " + shlex.quote(d) for d in [cfg["lib"]] + list(cfg.get("copybooks", [])))
    programs = {}
    for f in files:
        lst = os.path.join(build, os.path.splitext(os.path.basename(f))[0] + ".lst")
        cmd = f"cobc -fsyntax-only {std.group(1) if std else ''}{free} {incl} -t {shlex.quote(lst)} -ftsymbols {shlex.quote(f)}"
        subprocess.run(cmd, shell=True, capture_output=True, text=True)
        if not os.path.exists(lst):
            continue
        with open(lst, encoding="utf-8", errors="replace") as fh:
            listing = fh.read()
        for prog, items in parse_symbol_listing(listing).items():
            roots, warns = build_layout(items)
            programs[prog] = {"source": f.replace(os.sep, "/"), "items": roots, "warnings": warns}
    path = os.path.join(build, f"{suite}.layout.json")
    with open(path, "w", encoding="utf-8") as fh:
        json.dump({"schema": SCHEMA, "cobalto": VERSION, "suite": suite, "programs": programs}, fh,
                  ensure_ascii=False)
        fh.write("\n")
    return path, programs


def write_launch_json(path, configs):
    """Adds or replaces the Cobalto configurations in .vscode/launch.json
    without touching anyone else's."""
    data = {"version": "0.2.0", "configurations": []}
    if os.path.exists(path):
        try:
            with open(path, encoding="utf-8") as fh:
                data = json.load(fh)
        except ValueError:
            return False
    names = {c["name"] for c in configs}
    keep = [c for c in data.get("configurations", []) if c.get("name") not in names]
    data["configurations"] = configs + keep
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    return True
